"""File retrieval and TSV streaming service."""

from __future__ import annotations

import json
import logging
import tempfile
from dataclasses import dataclass

from sqlalchemy.orm import Session

from app.exceptions.types import (
    ExportNotFoundError,
    ExportNotReadyError,
    ExportReconciliationError,
)
from app.generators.activity_generator import generate_activity_records, generate_tsv_bytes
from app.repositories.export_repository import get_export_job, update_job_failed
from app.services.status_service import derive_status, ensure_completed_metrics
from app.utilities.checksum import compute_sha256
from app.utilities.date_range import generate_daily_dates
from app.utilities.datetime_utils import ensure_utc, utc_now

logger = logging.getLogger(__name__)


@dataclass
class ExportFileResult:
    """Export file generation result with metadata."""

    export_id: str
    number_of_days: int
    number_of_records: int
    checksum_hex: str
    file_bytes: bytes
    is_empty: bool


def get_export_file(
    db: Session,
    export_id: str,
    request_id: str,
) -> ExportFileResult:
    """Retrieve and verify the generated TSV file for a completed export job.

    Raises:
        ExportNotFoundError: If job doesn't exist.
        ExportNotReadyError: If job is not yet completed (HTTP 409).
        ExportReconciliationError: If generated bytes mismatch persisted metrics.
    """
    job = get_export_job(db, export_id)
    if not job:
        raise ExportNotFoundError(export_id)

    now = utc_now()
    status = derive_status(job, now)

    if status != "Completed":
        logger.warning(
            "File requested before completion: export_id=%s status=%s",
            export_id,
            status,
            extra={"export_id": export_id, "request_id": request_id},
        )
        raise ExportNotReadyError()

    # Ensure cached metrics exist
    job = ensure_completed_metrics(db, job)

    num_records = job.number_of_records or 0
    num_days = job.number_of_days

    # Zero-record scenario: HTTP 204 No Content
    if num_records == 0:
        logger.info("Export has 0 records, returning empty content for export_id=%s", export_id)
        return ExportFileResult(
            export_id=job.export_id,
            number_of_days=num_days,
            number_of_records=0,
            checksum_hex="",
            file_bytes=b"",
            is_empty=True,
        )

    start_at = ensure_utc(job.start_at) or utc_now()
    end_at = ensure_utc(job.end_at) or utc_now()

    # Generate records deterministically using persisted seed and counts
    daily_counts = json.loads(job.daily_record_counts_json or "[]")
    daily_dates = generate_daily_dates(start_at, end_at)
    seed = job.deterministic_seed or 0

    records = generate_activity_records(
        export_id=job.export_id,
        seed=seed,
        start_at=start_at,
        end_at=end_at,
        daily_counts=daily_counts,
        daily_dates=daily_dates,
    )

    # Use SpooledTemporaryFile for bounded memory handling
    with tempfile.SpooledTemporaryFile(max_size=10 * 1024 * 1024, mode="w+b") as spooled:
        tsv_bytes = generate_tsv_bytes(records)
        spooled.write(tsv_bytes)
        spooled.seek(0)
        file_bytes = spooled.read()

    generated_size = len(file_bytes)
    generated_checksum = compute_sha256(file_bytes)

    # Reconcile size and checksum against persisted metrics
    if generated_size != job.file_size_bytes or generated_checksum != job.file_checksum_sha256:
        logger.error(
            "Reconciliation mismatch for export_id=%s: size (%d vs %s), checksum (%s vs %s)",
            export_id,
            generated_size,
            job.file_size_bytes,
            generated_checksum,
            job.file_checksum_sha256,
        )
        update_job_failed(
            db,
            job,
            error_code="1037",
            error_message="Export generation or reconciliation failed",
        )
        raise ExportReconciliationError()

    # Clean hex checksum (strip 'sha256:' prefix if present for header)
    checksum_val = generated_checksum
    checksum_hex = checksum_val[len("sha256:"):] if checksum_val.startswith("sha256:") else checksum_val

    logger.info(
        "TSV file ready for download: export_id=%s size=%d records=%d checksum=%s",
        export_id,
        generated_size,
        num_records,
        checksum_hex,
        extra={"export_id": export_id, "request_id": request_id},
    )

    return ExportFileResult(
        export_id=job.export_id,
        number_of_days=num_days,
        number_of_records=num_records,
        checksum_hex=checksum_hex,
        file_bytes=file_bytes,
        is_empty=False,
    )
